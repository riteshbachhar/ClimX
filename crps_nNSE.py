def _as_kaggle_float(x: object) -> float:
    """
    Kaggle's metric notebook checks that ``score`` returns a built-in ``float``.
    Numpy scalars (e.g. ``np.float64``) and NaN/Inf must not leak through.
    """
    if isinstance(x, np.generic):
        y = float(x.item())
    else:
        y = float(x)
    if not math.isfinite(y):
        return -1.0
    return y


