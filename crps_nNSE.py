def _decode_mask():
    """Decode RLE literals → (mask int16 (nlat,nlon), lats float64 (nlat,))."""
    if not _MASK_RLE or _NLAT == 0:
        raise RuntimeError(
            "AR6 grid constants are empty. Paste _NLAT/_NLON/_LATS/_MASK_RLE from the notebook."
        )
    mask = np.repeat(
        np.array([v for v, _ in _MASK_RLE], dtype=np.int16),
        np.array([c for _, c in _MASK_RLE], dtype=np.int32),
    ).reshape(_NLAT, _NLON)
    lats = np.array(_LATS, dtype=np.float32)
    return mask, lats


def _crps_from_quantiles(
    obs: np.ndarray, quantiles: np.ndarray, levels: np.ndarray
) -> np.ndarray:
    """
    CRPS from discrete forecast quantiles (same as eval_uncertainty_indices).

    Trapezoidal integration in τ; quantile levels need not be uniform.
    obs: (...) observation; quantiles: (..., K); levels: (K,).
    """
    # Keep float32 throughout (safe + smaller memory footprint).
    levels = np.asarray(levels, dtype=np.float32).ravel()
    k = int(levels.size)
    if k == 0:
        return np.full_like(obs, np.nan, dtype=np.float32)

    # Avoid hidden copies: asarray(copy=False) not available; rely on dtype match.
    obs = np.asarray(obs, dtype=np.float32)
    obs = np.squeeze(obs)
    q = np.asarray(quantiles, dtype=np.float32)
    while q.ndim > 2:
        sq_axis = next((ax for ax in range(q.ndim - 1) if q.shape[ax] == 1), None)
        if sq_axis is None:
            break
        q = np.squeeze(q, axis=sq_axis)

    order = np.argsort(levels)
    tau = levels[order]
    # Fast path for last-axis reindexing without broadcasting `order` to q.shape.
    q = q[..., order]

    tau_ext = np.concatenate((np.array([0.0], dtype=np.float32), tau, np.array([1.0], dtype=np.float32)))
    y = obs[..., np.newaxis]  # view, no copy
    q0 = q[..., :1]
    qk = q[..., -1:]
    q_ext = np.concatenate([q0, q, qk], axis=-1)

    # float32 math to reduce memory. (lt is 0/1 indicator.)
    lt = (y < q_ext).astype(np.float32, copy=False)
    # tau_ext broadcasts to (..., K+2) without materializing.
    pinball = (y - q_ext) * (tau_ext - lt)
    dt = np.diff(tau_ext).astype(np.float32, copy=False)
    trap = (pinball[..., :-1] + pinball[..., 1:]) * (0.5 * dt)
    crps = (2.0 * np.nansum(trap, axis=-1)).astype(np.float32, copy=False)
    return np.where(np.isfinite(obs), crps, np.nan)


def _uq_column_name(index_name: str, q: float) -> str:
    """Canonical wide-column name (matches ``kaggle_submission_uq._quantile_column_name``)."""
    return f"{index_name}_{q}"


def _expected_uq_column_names() -> tuple[str, ...]:
    """All ``{index}_{quantile}`` columns required in a submission."""
    return tuple(
        _uq_column_name(idx, q)
        for idx in CLIMX_INDEX_COLUMNS
        for q in QUANTILE_LEVELS
    )


def _validate_submission_uq_columns(columns: pd.Index) -> dict[str, list[tuple[float, str]]]:
    """
    Ensure every (index, quantile) in the schema has a column in the submission.

    Returns index_name -> ``[(quantile_level, column_name), ...]`` in ``QUANTILE_LEVELS`` order.
    """
    col_set = {str(c) for c in columns}
    expected = _expected_uq_column_names()
    missing = [n for n in expected if n not in col_set]
    if missing:
        raise ParticipantVisibleError(
            f"Submission missing {len(missing)} required UQ column(s), e.g. {missing[:8]!r}."
        )

    return {
        idx: [(q, _uq_column_name(idx, q)) for q in QUANTILE_LEVELS]
        for idx in CLIMX_INDEX_COLUMNS
    }


def _assert_uq_columns_numeric(df: pd.DataFrame, uq_by_index: dict[str, list[tuple[float, str]]]) -> None:
    for pairs in uq_by_index.values():
        for _q, name in pairs:
            if not pd.api.types.is_numeric_dtype(df[name]):
                raise ParticipantVisibleError(f"Submission UQ column {name!r} must be numeric.")


def load_uq_table(path):
    """Load a participant submission CSV or Parquet (path suffix decides engine)."""
    p = Path(path)
    suf = p.suffix.lower()
    if suf in (".parquet", ".pq"):
        return pd.read_parquet(p)
    if suf in (".csv", ".txt"):
        return pd.read_csv(p)
    raise ParticipantVisibleError(f"Unsupported file type for {p}; use .csv or .parquet.")


def _score_impl(
    solution: pd.DataFrame,
    submission: pd.DataFrame,
    row_id_column_name: str = "row_id",
) -> float:
    if row_id_column_name not in submission.columns:
        raise ParticipantVisibleError(f"Submission missing {row_id_column_name!r}.")

    index_names = CLIMX_INDEX_COLUMNS
    n = len(solution)
    if len(submission) != n:
        raise ParticipantVisibleError(
            f"Row count mismatch: solution has {n}, submission has {len(submission)}."
        )

    solution = solution.sort_values(row_id_column_name, kind="mergesort").reset_index(drop=True)
    submission = submission.sort_values(row_id_column_name, kind="mergesort").reset_index(drop=True)
    if not np.array_equal(
        solution[row_id_column_name].to_numpy(), submission[row_id_column_name].to_numpy()
    ):
        raise ParticipantVisibleError(
            f"{row_id_column_name} row id values differ between solution and submission after sorting. Submission needs 0 to {n-1}."
        )

    uq_by_index = _validate_submission_uq_columns(submission.columns)
    _assert_uq_columns_numeric(submission, uq_by_index)

    region_mask, lats = _decode_mask()
    nlat, nlon = region_mask.shape
    t_steps = n // (nlat * nlon)
    cos_w = np.cos(np.deg2rad(lats.astype(np.float32, copy=False))).astype(np.float32, copy=False)
    unique_regions = np.unique(region_mask[region_mask >= 0])

    per_index_scores = []

    for idx in index_names:
        bcol = f"{idx}{_BASE_CRPS_SUFFIX}"
        # Keep the ground truth as a flat float32 vector and reshape only per-chunk
        # to avoid holding multiple large views/temporaries at once.
        gt_flat = solution[idx].to_numpy(dtype=np.float32, copy=False)
        
        # base_flat = solution[bcol].to_numpy(dtype=np.float32, copy=False)
        # base_t = base_flat.reshape(t_steps, nlat, nlon)
        # base_map = np.nanmean(base_t, axis=0, dtype=np.float32)

        # # Release the large time-expanded baseline array ASAP.
        # del base_t, base_flat
        # gc.collect()

        base_flat = solution[bcol].to_numpy(dtype=np.float32, copy=False)

        base_map = np.zeros((nlat, nlon), dtype=np.float32)
        count = np.zeros((nlat, nlon), dtype=np.int32)

        for t in range(t_steps):
            slice_ = base_flat[t * nlat * nlon : (t + 1) * nlat * nlon]
            slice_ = slice_.reshape(nlat, nlon)

            valid = np.isfinite(slice_)
            base_map += np.where(valid, slice_, 0.0).astype(np.float32, copy=False)
            count += valid.astype(np.int32, copy=False)

        # Match np.nanmean semantics: if count==0 at a pixel, result is NaN.
        base_map = np.divide(
            base_map,
            count,
            out=np.full((nlat, nlon), np.nan, dtype=np.float32),
            where=(count > 0),
        )

        del base_flat, count
        gc.collect()


        q_levels, col_names = zip(*uq_by_index[idx])
        q_arr = np.asarray(q_levels, dtype=np.float32)
        # Pull the submission quantiles in small chunks to avoid materializing the
        # full (n_rows × n_quantiles) array in memory for each index.
        #
        # chunk_size trades runtime for peak memory. Kaggle environments can be tight,
        # so keep the default conservative.
        chunk_size = 4  # time steps per chunk
        # Use float64 for the time-sum accumulator to reduce sensitivity to
        # chunking / summation order (keeps metric logic identical).
        accum = np.zeros((nlat, nlon), dtype=np.float64)
        count = np.zeros((nlat, nlon), dtype=np.int32)

        cols_idx = [submission.columns.get_loc(c) for c in col_names]

        for t0 in range(0, t_steps, chunk_size):
            t1 = min(t0 + chunk_size, t_steps)

            r0 = t0 * nlat * nlon
            r1 = t1 * nlat * nlon

            gt_chunk = gt_flat[r0:r1].reshape(t1 - t0, nlat, nlon)
            # Extract only the needed rows/columns, then reshape to (chunk, lat, lon, K).
            pred_chunk = submission.iloc[r0:r1, cols_idx].to_numpy(
                dtype=np.float32, copy=False
            )
            pred_chunk = pred_chunk.reshape(t1 - t0, nlat, nlon, len(q_arr))

            crps_chunk = _crps_from_quantiles(gt_chunk, pred_chunk, q_arr)

            valid = np.isfinite(crps_chunk)
            accum += np.nansum(crps_chunk, axis=0, dtype=np.float64)
            count += np.sum(valid, axis=0, dtype=np.int32)

            del gt_chunk, pred_chunk, crps_chunk
            gc.collect()

        # Match np.nanmean semantics: if count==0 at a pixel, result is NaN.
        mean_crps_new = np.divide(
            accum,
            count,
            out=np.full((nlat, nlon), np.nan, dtype=np.float64),
            where=(count > 0),
        ).astype(np.float32, copy=False)

        del accum, count
        gc.collect()

        # Free large intermediates before region loop.
        del q_arr, gt_flat
        gc.collect()


        # Keep float32 arrays; only accumulate region scalars as python floats.
        base_np = np.asarray(base_map, dtype=np.float32)
        new_np = np.asarray(mean_crps_new, dtype=np.float32)
        del base_map, mean_crps_new
        gc.collect()

        region_scores = []
        cos_w_col = cos_w[:, None]

        for rc in unique_regions:
            in_region = region_mask == rc
            valid = (
                in_region
                & np.isfinite(base_np)
                & np.isfinite(new_np)
                & (base_np > 0.0)
            )
            if not np.any(valid):
                continue
            # Weighting uses cos(lat) for area, applied only on valid cells.
            wv = cos_w_col * valid.astype(np.float32, copy=False)
            # Match previous behavior: float32 accumulation for total weight.
            total_w = float(np.sum(wv, dtype=np.float32))
            if total_w <= 0.0:
                continue
            # Keep products float32 to reduce peak memory.
            base_reg = float(np.nansum((base_np * wv)) / total_w)
            new_reg = float(np.nansum((new_np * wv)) / total_w)
            if not np.isfinite(base_reg) or base_reg <= 0.0:
                continue
            r2_uq_reg = 1.0 - (new_reg / base_reg)
            nnse_reg = r2_uq_reg / max(2.0 - r2_uq_reg, 1e-6)
            region_scores.append(float(nnse_reg))

        if region_scores:
            per_index_scores.append(_as_kaggle_float(np.mean(region_scores)))

        # Free per-index maps before the next index iteration.
        del base_np, new_np, region_scores
        gc.collect()

    if not per_index_scores:
        return _as_kaggle_float(0.0)
    return _as_kaggle_float(np.nanmean(per_index_scores))

def score(
    solution: pd.DataFrame,
    submission: pd.DataFrame,
    row_id_column_name: str,
) -> float:
    """
    UQ leaderboard score in [-1, 1], mean over indices (each index: mean over AR6 regions).

    The curated ``solution`` is read as-is. Checks on ``submission``: required UQ
    columns exist and are numeric; row count matches ``solution``; ``row_id``
    values match after sorting by ``row_id``.

    Any failure returns ``-1.0`` so Kaggle metric notebooks can validate without aborting.
    """
    
    num_cols = submission.select_dtypes(include=[np.number]).columns
    num_cols = [c for c in num_cols if c != row_id_column_name]

    submission[num_cols] = submission[num_cols].astype(np.float32)

    try:
        return float(_score_impl(solution, submission, row_id_column_name))
    except Exception:
        return float(-1.0)