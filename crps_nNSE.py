"""
ClimX Challenge — Region-wise UQ metric (CRPS skill, baseline-normalized nNSE).

Final score S ∈ (-1, 1]:  higher is better.
Let  T  = number of time steps,  V = set of indices,  K = set of AR6 land regions,
     τ_1 < … < τ_m = QUANTILE_LEVELS (m = 9, non-uniform).
Submissions give m predictive quantiles q_ijvt(τ) per cell; the truth is a scalar y_ijvt.

Pinball (quantile) loss and its τ-integral give CRPS:

    ρ_τ(y, q)   = (y - q) · (τ - 1[y < q])

    CRPS_ijvt   = 2 ∫₀¹ ρ_τ(y_ijvt, q_ijvt(τ)) dτ
                ≈ 2 · trapz over τ̃ = (0, τ_1, …, τ_m, 1), with the predictive
                  CDF held flat outside [τ_1, τ_m] (q(0) := q(τ_1), q(1) := q(τ_m))

For each grid cell (i, j) valid for index v in region k
[baseline CRPS finite and > 0, submission CRPS finite]:

    C_ijv       = mean_t CRPS_ijvt                          (NaN-skipping)
    B_ijv       = mean_t CRPS^base_ijvt                      (from {v}_base_CRPS)

    C_kv        = Σ_{(i,j)∈k,valid}  cos(φ_i) · C_ijv       (area-weighted region mean)
                  ─────────────────────────────────────
                  Σ_{(i,j)∈k,valid}  cos(φ_i)

    B_kv        = same weighted mean applied to B_ijv

    R²_kv       = 1 - C_kv / B_kv                            (unbounded below)
    nNSE_kv     = R²_kv / (2 - R²_kv)                        ∈ (-1, 1]

    S_v         = mean of nNSE_kv  over regions k with ≥1 valid cell

    S           = mean of S_v  over all indices v             ← returned score

Note the reduction order: the skill ratio is formed *after* the regional spatial
average, not per cell, so cells with larger absolute CRPS dominate R²_kv.

Key properties
--------------
  C_kv = 0      → nNSE =  1     perfect (degenerate predictive distribution at y)
  C_kv = B_kv   → nNSE =  0     matching the baseline's CRPS
  C_kv → ∞      → nNSE → -1     worst possible
  CRPS is minimized by the true predictive distribution, so both over-confident
  and needlessly wide quantile spreads are penalized.

Submission / solution columns
-----------------------------
  Submission: one column per (index, quantile), named {index}_{quantile} using
  Python float repr — ``TXx_0.05``, ``TXx_0.1``, ``TXx_0.2``, … (not ``TXx_0.10``).
  Solution: one truth column per index plus one {index}_base_CRPS column.
  Rows are complete 192 × 288 maps in (time, lat, lon) order, row_id = 0 … N-1.

Grid data
---------
  _NLAT, _NLON, _LATS, _MASK_RLE are generated by the notebook rasterize cell.
  Paste the printed block here to update the embedded AR6 grid.
"""

